def detect_item_condition(text: str) -> ItemCondition | None:
    """
    Определяет состояние товара по тексту сообщения.
    
    Приоритет:
    1. "повреждён" - если есть признаки повреждения/брака
    2. "не использовался" - если явно указано, что не трогали
    3. "использовался" - если есть признаки использования
    4. "вскрыт" - если только вскрыли без использования
    
    Args:
        text: Текст сообщения пользователя
        
    Returns:
        Определенное состояние товара или None если не удалось определить
    """
    text_lower = text.lower()
    
    # Проверяем наличие маркеров для каждого состояния
    found_conditions = {}
    
    for condition, markers in CONDITION_MARKERS.items():
        for marker in markers:
            if marker in text_lower:
                if condition not in found_conditions:
                    found_conditions[condition] = []
                found_conditions[condition].append(marker)
    
    # Если ничего не найдено
    if not found_conditions:
        return None
    
    # Приоритет 1: Повреждён (самый важный)
    if "повреждён" in found_conditions:
        return "повреждён"
    
    # Приоритет 2: Не использовался (явный отказ от использования)
    if "не использовался" in found_conditions:
        return "не использовался"
    
    # Приоритет 3: Использовался
    if "использовался" in found_conditions:
        return "использовался"
    
    # Приоритет 4: Вскрыт
    if "вскрыт" in found_conditions:
        return "вскрыт"
    
    return None


def should_skip_condition_question(return_reason: str | None, detected_condition: ItemCondition | None) -> bool:
    """
    Определяет, нужно ли пропустить вопрос о состоянии товара.
    
    Args:
        return_reason: Причина возврата
        detected_condition: Автоматически определенное состояние
        
    Returns:
        True если вопрос можно пропустить, False если нужно спросить
    """
    if not return_reason:
        return False
    
    # Если состояние определено автоматически, пропускаем вопрос
    if detected_condition:
        return True
    
    return False
