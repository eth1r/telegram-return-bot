"""
Тестовый скрипт для проверки автоопределения состояния товара.
"""

from services.assistant.condition_detector import detect_item_condition


def test_condition_detection():
    """Тестирует автоопределение состояния товара"""
    
    test_cases = [
        # Повреждён
        ("тарелка пришла со сколом", "повреждён"),
        ("товар сломан", "повреждён"),
        ("экран не работает", "повреждён"),
        ("пришёл с браком", "повреждён"),
        ("товар повреждён", "повреждён"),
        ("с трещиной", "повреждён"),
        ("разбилась", "повреждён"),
        
        # Вскрыт
        ("вскрыл упаковку", "вскрыт"),
        ("распаковал", "вскрыт"),
        ("открыл упаковку", "вскрыт"),
        
        # Использовался
        ("пользовался неделю", "использовался"),
        ("носил пару раз", "использовался"),
        ("включал", "использовался"),
        
        # Не использовался
        ("не открывал", "не использовался"),
        ("в упаковке", "не использовался"),
        ("новый", "не использовался"),
        ("не трогал", "не использовался"),
        
        # Приоритет: повреждён > не использовался
        ("пришёл повреждённым, не использовал", "повреждён"),
        
        # Не определено
        ("не подошёл размер", None),
        ("передумал", None),
    ]
    
    print("=" * 60)
    print("ТЕСТ АВТООПРЕДЕЛЕНИЯ СОСТОЯНИЯ ТОВАРА")
    print("=" * 60)
    
    passed = 0
    failed = 0
    
    for message, expected in test_cases:
        result = detect_item_condition(message)
        status = "✅" if result == expected else "❌"
        
        if result == expected:
            passed += 1
        else:
            failed += 1
        
        print(f"\n{status} Сообщение: '{message}'")
        print(f"   Ожидалось: {expected}")
        print(f"   Получено:  {result}")
    
    print("\n" + "=" * 60)
    print(f"ИТОГО: {passed} пройдено, {failed} провалено")
    print("=" * 60)


if __name__ == "__main__":
    test_condition_detection()
